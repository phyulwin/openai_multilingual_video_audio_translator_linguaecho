// main.tsx — React entry point and recoverable rendering error boundary.
import { Component, type ReactNode } from "react";
import { createRoot } from "react-dom/client";
import App from "./App";
import "./styles.css";
class ErrorBoundary extends Component<
  { children: ReactNode },
  { failed: boolean }
> {
  // A failed component cannot leave an unexplained blank application.
  state = { failed: false };
  static getDerivedStateFromError() {
    return { failed: true };
  }
  render() {
    return this.state.failed ? (
      <main className="fatal">
        <h1>Something interrupted your workspace.</h1>
        <p>Your saved projects are still on this computer.</p>
        <button onClick={() => location.reload()}>Reload LinguaEcho</button>
      </main>
    ) : (
      this.props.children
    );
  }
}
createRoot(document.getElementById("root")!).render(
  <ErrorBoundary>
    <App />
  </ErrorBoundary>,
);
